    def test_bold_style_inheritance_and_normal_override_are_resolved(self):
        path = self.prepare("CU-T06")
        common = ('<style:style style:name="Parent" style:family="paragraph">'
                  '<style:text-properties fo:font-weight="700"/></style:style>')
        automatic = '<style:style style:name="Child" style:family="paragraph" style:parent-style-name="Parent"/>'
        body = f'<text:h text:outline-level="2">{U}</text:h><text:p text:style-name="Child">{R}</text:p>'
        self.assertTrue(self.check("CU-T06", path, package(body, automatic, common))["artifact_matches"])
        normal = ('<style:style style:name="Plain" style:family="text">'
                  '<style:text-properties fo:font-weight="normal"/></style:style>')
        body = body.replace(R, f'<text:span text:style-name="Plain">{R}</text:span>')
        self.assertFalse(self.check("CU-T06", path, package(body, automatic + normal, common))["artifact_matches"])
        for styles in [BOLD + BOLD, BOLD.replace('fo:font-weight="bold"', 'fo:font-weight="inherit"'),
                       '<style:style style:name="Bold" style:family="text" style:parent-style-name="Bold"/>',
                       BOLD.replace('</style:style>', '<style:map style:condition="true" '
                                    'style:apply-style-name="Other"/></style:style>')]:
            self.assertIsNone(self.check("CU-T06", path, package(HEADING_BODY, styles))["artifact_matches"])
        default_text = ('<style:default-style style:family="text">'
                        '<style:text-properties fo:font-weight="normal"/></style:default-style>')
        self.assertIsNone(self.check("CU-T06", path, package(HEADING_BODY, BOLD, default_text))["artifact_matches"])
        conditional = HEADING_BODY.replace('<text:p>', '<text:p text:cond-style-name="Other">')
        self.assertIsNone(self.check("CU-T06", path, package(conditional, BOLD))["artifact_matches"])

