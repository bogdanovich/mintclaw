    def test_file_and_marker_identity_guards_are_reused(self):
        for kind in ("symlink", "hardlink", "fifo", "directory", "missing"):
            with self.subTest(kind=kind):
                path = self.parent / kind
                fixtures.prepare("CU-T06", path)
                source = path / "private"
                source.write_bytes(package(HEADING_BODY, BOLD))
                candidate = path / "document.odt"
                if kind == "symlink":
                    candidate.symlink_to(source)
                elif kind == "hardlink":
                    os.link(source, candidate)
                elif kind == "fifo":
                    os.mkfifo(candidate)
                elif kind == "directory":
                    candidate.mkdir()
                self.assertIsNone(fixtures.check_artifact("CU-T06", path)["artifact_matches"])
        path = self.prepare("CU-T06")
        (path / "document.odt").write_bytes(package(HEADING_BODY, BOLD))
        marker = path / fixtures.MARKER
        original = marker.read_bytes()
        self.assertIsNone(fixtures.check_artifact("CU-T07", path)["artifact_matches"])
        for key, value in [("fixture_revision", "0" * 64), ("root_inode", 0), ("run_id", "bad")]:
            record = json.loads(original)
            record[key] = value
            marker.write_text(json.dumps(record))
            self.assertIsNone(fixtures.check_artifact("CU-T06", path)["artifact_matches"])
        marker.write_bytes(original[:-1] + b',"task_id":"CU-T06"}')
        self.assertIsNone(fixtures.check_artifact("CU-T06", path)["artifact_matches"])

