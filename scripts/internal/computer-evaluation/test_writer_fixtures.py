import writer_fixtures as fixtures


U = "MintClaw — Привет 世界 café 👩‍💻"
R = "Обновлено — naïve 🌿"
NAMESPACES = ('xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" '
              'xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" '
              'xmlns:style="urn:oasis:names:tc:opendocument:xmlns:style:1.0" '
              'xmlns:table="urn:oasis:names:tc:opendocument:xmlns:table:1.0" '
              'xmlns:fo="urn:oasis:names:tc:opendocument:xmlns:xsl-fo-compatible:1.0"')
BOLD = '<style:style style:name="Bold" style:family="text"><style:text-properties fo:font-weight="bold"/></style:style>'
ORDERED = ('<text:list-style style:name="Numbered"><text:list-level-style-number text:level="1" '
           'style:num-format="1"/></text:list-style>')
HEADING_BODY = (f'<text:h text:outline-level="1">{U}</text:h>'
                f'<text:p><text:span text:style-name="Bold">{R}</text:span></text:p>')
LIST_BODY = (f'<text:p>{U}</text:p><text:list text:style-name="Numbered">'
             '<text:list-item><text:p>alpha</text:p></text:list-item>'
             '<text:list-item><text:p>Привет</text:p></text:list-item>'
             '<text:list-item><text:p>世界</text:p></text:list-item></text:list>')
TABLE_BODY = '<table:table><table:table-column table:number-columns-repeated="3"/>' + ''.join(
    '<table:table-row>' + ''.join(f'<table:table-cell><text:p>r{row}c{column}</text:p></table:table-cell>'
                                for column in range(1, 4)) + '</table:table-row>'
    for row in range(1, 4)) + '</table:table>'


def package(body, automatic="", common="", replacements=None):
    # Independent package construction: expected results are literal task
    # documents, not projections generated by the implementation under test.
    content = (f'<office:document-content {NAMESPACES} office:version="1.3">'
               f'<office:automatic-styles>{automatic}</office:automatic-styles>'
               f'<office:body><office:text>{body}</office:text></office:body></office:document-content>')
    styles = (f'<office:document-styles {NAMESPACES} office:version="1.3">'
              f'<office:styles>{common}</office:styles></office:document-styles>')
    manifest = ('<manifest:manifest xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0">'
                '<manifest:file-entry manifest:full-path="/" '
                'manifest:media-type="application/vnd.oasis.opendocument.text"/>'
                '<manifest:file-entry manifest:full-path="content.xml" manifest:media-type="text/xml"/>'
                '<manifest:file-entry manifest:full-path="styles.xml" manifest:media-type="text/xml"/>'
                '</manifest:manifest>')
    entries = {"mimetype": b"application/vnd.oasis.opendocument.text", "content.xml": content.encode(),
               "styles.xml": styles.encode(), "META-INF/manifest.xml": manifest.encode()}
    entries.update(replacements or {})
    output = BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_STORED) as archive:
        for name, data in entries.items():
            if data is not None:
                archive.writestr(name, data)
    return output.getvalue()


class WriterFixtureTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="mintclaw-writer-oracle-")
        self.addCleanup(self.temporary.cleanup)
        self.parent = Path(self.temporary.name)

    def prepare(self, task):
        path = self.parent / task
        result = fixtures.prepare(task, path)
        self.assertFalse(result["native_task_qualified"])
        self.assertEqual(path.stat().st_mode & 0o777, 0o700)
        return path

    def check(self, task, path, data):
        candidate = path / "document.odt"
        candidate.write_bytes(data)
        before = candidate.stat()
        result = fixtures.check_artifact(task, path)
        self.assertEqual(fixtures.shared.file_identity(before), fixtures.shared.file_identity(candidate.stat()))
        self.assertFalse(result["native_task_qualified"])
        self.assertNotIn(U, json.dumps(result, ensure_ascii=False))
        self.assertNotIn(R, json.dumps(result, ensure_ascii=False))
        return result

    def test_frozen_revision_and_task_data(self):
        self.assertEqual(fixtures.FIXTURE_REVISION, "e083268149089218b2b26a85b175a255643af256ab212083e3077ebdbd5dfb4f")
        self.assertEqual(tuple(fixtures.TASKS), ("CU-T06", "CU-T07", "CU-T08"))
        with self.assertRaises(TypeError):
            fixtures.TASKS["new"] = None
        with self.assertRaises(FrozenInstanceError):
            fixtures.TASKS["CU-T07"].seed = "changed"
        self.assertEqual(fixtures.TASKS["CU-T06"].expected, (("heading", U), ("paragraph", R, True)))
        self.assertEqual(fixtures.TASKS["CU-T07"].seed, f"<text:p>{U}</text:p>")
        self.assertEqual(fixtures.TASKS["CU-T08"].seed, "<text:p/>")
        self.assertEqual(fixtures.seed_odt("<text:p/>"), fixtures.seed_odt("<text:p/>"))

    def test_prepare_seeds_only_existing_documents_and_never_adopts_a_directory(self):
        for task in fixtures.TASKS:
            with self.subTest(task=task):
                path = self.prepare(task)
                self.assertEqual((path / "document.odt").exists(), task != "CU-T06")
                self.assertIsNot(fixtures.check_artifact(task, path)["artifact_matches"], True)
                (path / "preserve").write_bytes(b"owned canary")
                with self.assertRaises(FileExistsError):
                    fixtures.prepare(task, path)
                self.assertEqual((path / "preserve").read_bytes(), b"owned canary")

    def test_independent_semantic_documents_match_without_claiming_native_passes(self):
        for task, body, styles in [("CU-T06", HEADING_BODY, BOLD), ("CU-T07", LIST_BODY, ORDERED),
                                   ("CU-T08", TABLE_BODY, "")]:
            path = self.prepare(task)
            result = self.check(task, path, package(body, styles))
            self.assertTrue(result["artifact_matches"], result)
            self.assertNotIn("reason", result)

    def test_visible_text_without_heading_or_complete_bold_does_not_match(self):
        path = self.prepare("CU-T06")
        for body in [HEADING_BODY.replace('text:h text:outline-level="1"', "text:p").replace("</text:h>", "</text:p>"),
                     f'<text:h text:outline-level="1">{U}</text:h><text:p>{R}</text:p>',
                     HEADING_BODY.replace(R, R[:-1]) + f"<text:p>{R[-1]}</text:p>",
                     HEADING_BODY + "<text:p>extra</text:p>", HEADING_BODY.replace("naïve", "naive")]:
            self.assertIsNot(self.check("CU-T06", path, package(body, BOLD))["artifact_matches"], True)

    def test_bold_style_inheritance_and_normal_override_are_resolved(self):
        path = self.prepare("CU-T06")
        common = ('<style:style style:name="Parent" style:family="paragraph">'
                  '<style:text-properties fo:font-weight="700"/></style:style>')
        automatic = '<style:style style:name="Child" style:family="paragraph" style:parent-style-name="Parent"/>'
        body = f'<text:h text:outline-level="2">{U}</text:h><text:p text:style-name="Child">{R}</text:p>'
        self.assertTrue(self.check("CU-T06", path, package(body, automatic, common))["artifact_matches"])
        normal = ('<style:style style:name="Plain" style:family="text">'
                  '<style:text-properties fo:font-weight="normal"/></style:style>')
        body = body.replace(R, f'<text:span text:style-name="Plain">{R}</text:span>')
        self.assertFalse(self.check("CU-T06", path, package(body, automatic + normal, common))["artifact_matches"])
        for styles in [BOLD + BOLD, BOLD.replace('fo:font-weight="bold"', 'fo:font-weight="inherit"'),
                       '<style:style style:name="Bold" style:family="text" style:parent-style-name="Bold"/>',
                       BOLD.replace('</style:style>', '<style:map style:condition="true" '
                                    'style:apply-style-name="Other"/></style:style>')]:
            self.assertIsNone(self.check("CU-T06", path, package(HEADING_BODY, styles))["artifact_matches"])
        default_text = ('<style:default-style style:family="text">'
                        '<style:text-properties fo:font-weight="normal"/></style:default-style>')
        self.assertIsNone(self.check("CU-T06", path, package(HEADING_BODY, BOLD, default_text))["artifact_matches"])
        conditional = HEADING_BODY.replace('<text:p>', '<text:p text:cond-style-name="Other">')
        self.assertIsNone(self.check("CU-T06", path, package(conditional, BOLD))["artifact_matches"])

    def test_real_ordered_list_preserves_original_paragraph_and_item_order(self):
        path = self.prepare("CU-T07")
        for body, style in [(LIST_BODY, ORDERED.replace("list-level-style-number", "list-level-style-bullet")),
                            (LIST_BODY.replace("Привет", "wrong"), ORDERED),
                            (LIST_BODY.replace(U, "changed"), ORDERED),
                            (LIST_BODY.replace("alpha", "世界").replace("Привет", "alpha"), ORDERED),
                            (f"<text:p>{U}</text:p><text:p>1. alpha</text:p>"
                             "<text:p>2. Привет</text:p><text:p>3. 世界</text:p>", "")]:
            self.assertIsNot(self.check("CU-T07", path, package(body, style))["artifact_matches"], True)

    def test_real_table_rejects_flat_text_duplicates_merges_and_wrong_geometry(self):
        path = self.prepare("CU-T08")
        for body in [TABLE_BODY.replace("r2c2", "r2c1"), TABLE_BODY.replace("r3c3", "wrong"),
                     TABLE_BODY.replace('repeated="3"', 'repeated="4"'),
                     TABLE_BODY.replace("<table:table-cell>", '<table:table-cell table:number-columns-spanned="2">', 1),
                     "<text:p>r1c1 r1c2 r1c3 r2c1 r2c2 r2c3 r3c1 r3c2 r3c3</text:p>",
                     TABLE_BODY + "<text:p>extra</text:p>"]:
            self.assertIsNot(self.check("CU-T08", path, package(body))["artifact_matches"], True)
        result = self.check("CU-T08", path, package("<text:p/>" + TABLE_BODY + "<text:p/>"))
        self.assertTrue(result["artifact_matches"])

    def test_bounded_packages_xml_entities_depth_nodes_and_duplicate_parts(self):
        path = self.prepare("CU-T06")
        malformed = [b"not a zip", package(HEADING_BODY, BOLD, replacements={"mimetype": b"text/plain"}),
                     package(HEADING_BODY, BOLD, replacements={"META-INF/manifest.xml": None}),
                     package(HEADING_BODY, BOLD, replacements={"content.xml": b"x" * (fixtures.MAX_XML_BYTES + 1)}),
                     package(HEADING_BODY, BOLD, replacements={
                         "content.xml": b'<!DOCTYPE x [<!ENTITY x "boom">]><x>&x;</x>'}),
                     package(HEADING_BODY, BOLD, replacements={"content.xml": b"<x>" * 66 + b"</x>" * 66}),
                     package(HEADING_BODY, BOLD, replacements={"content.xml": b"<x>" + b"<y/>" * 4096 + b"</x>"}),
                     package(HEADING_BODY, BOLD, replacements={"content.xml": b"\xff"}),
                     package(HEADING_BODY, BOLD, replacements={"../unexpected": b"x"}),
                     b"x" * (fixtures.MAX_ARTIFACT_BYTES + 1)]
        duplicate = BytesIO(package(HEADING_BODY, BOLD))
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", UserWarning)
            with zipfile.ZipFile(duplicate, "a") as archive:
                archive.writestr("content.xml", b"private canary")
        malformed.append(duplicate.getvalue())
        for data in malformed:
            result = self.check("CU-T06", path, data)
            self.assertIsNone(result["artifact_matches"], result)
            self.assertIn("reason", result)
            self.assertNotIn("private canary", json.dumps(result))

    def test_file_and_marker_identity_guards_are_reused(self):
        for kind in ("symlink", "hardlink", "fifo", "directory", "missing"):
            with self.subTest(kind=kind):
                path = self.parent / kind
                fixtures.prepare("CU-T06", path)
                source = path / "private"
                source.write_bytes(package(HEADING_BODY, BOLD))
                candidate = path / "document.odt"
                if kind == "symlink":
                    candidate.symlink_to(source)
                elif kind == "hardlink":
                    os.link(source, candidate)
                elif kind == "fifo":
                    os.mkfifo(candidate)
                elif kind == "directory":
                    candidate.mkdir()
                self.assertIsNone(fixtures.check_artifact("CU-T06", path)["artifact_matches"])
        path = self.prepare("CU-T06")
        (path / "document.odt").write_bytes(package(HEADING_BODY, BOLD))
        marker = path / fixtures.MARKER
        original = marker.read_bytes()
        self.assertIsNone(fixtures.check_artifact("CU-T07", path)["artifact_matches"])
        for key, value in [("fixture_revision", "0" * 64), ("root_inode", 0), ("run_id", "bad")]:
            record = json.loads(original)
            record[key] = value
            marker.write_text(json.dumps(record))
            self.assertIsNone(fixtures.check_artifact("CU-T06", path)["artifact_matches"])
        marker.write_bytes(original[:-1] + b',"task_id":"CU-T06"}')
        self.assertIsNone(fixtures.check_artifact("CU-T06", path)["artifact_matches"])

    def test_candidate_mutation_during_read_is_unverifiable(self):
        path = self.prepare("CU-T06")
        (path / "document.odt").write_bytes(package(HEADING_BODY, BOLD))
        original_read = os.read

        def mutate(descriptor, maximum):
            data = original_read(descriptor, maximum)
            if data.startswith(b"PK"):
                (path / "document.odt").write_bytes(b"changed")
            return data

        with mock.patch.object(fixtures.shared.os, "read", side_effect=mutate):
            result = fixtures.check_artifact("CU-T06", path)
        self.assertIsNone(result["artifact_matches"])
        self.assertEqual(result["reason"], "artifact_changed")

    def test_cli_exit_codes_and_protected_reports(self):
        path = self.parent / "cli"

        def invoke(operation):
            return subprocess.run(
                [sys.executable, fixtures.__file__, operation, "--task", "CU-T06", "--run-directory", str(path)],
                capture_output=True, text=True, timeout=5, check=False,
            )

        self.assertEqual(invoke("prepare").returncode, 0)
        self.assertEqual(invoke("prepare").returncode, 2)
        self.assertEqual(invoke("check-artifact").returncode, 2)
        (path / "document.odt").write_bytes(package("<text:p>wrong</text:p>"))
        self.assertEqual(invoke("check-artifact").returncode, 1)
        (path / "document.odt").write_bytes(package(HEADING_BODY, BOLD))
        result = invoke("check-artifact")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue(json.loads(result.stdout)["artifact_matches"])
        self.assertFalse(json.loads(result.stdout)["native_task_qualified"])
        self.assertEqual(result.stderr, "")
